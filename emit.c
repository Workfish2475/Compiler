// Pre: Pointer to A_VAR node and pointer to MIPS asm file 
// Post: Prints instructions to MIPS asm file depending on node scope as well as the subtype (if array)
void EMIT_VAR(ASTnode *p, FILE *fp)
{
	char s[100];

	// Checking for global var
	if (p->symbol->level == 0){
		// Get the direct address of global var
		if (p->symbol->SubType == SYM_ARRAY){
			EMIT_EXPR(p->s1, fp);
		
			p->label = createLabel();

			emit(fp, "", "move $a1, $a0", "var copy index array in a1");

			emit(fp, "", "add $a0, $a0, 1", "");
			sprintf(s, "li $t1, %d", p->symbol->mysize);
			emit(fp, "", s, "");
			emit(fp, "", "slt $t0, $t1, $a0", "");
			sprintf(s, "beq $t0, $0, %s", p->label);
			emit(fp, "", s, "");

			emit(fp, "", "li $v0, 10", "");
			emit(fp, "", "syscall", "");

			fprintf(fp, "\n");
			emit(fp, p->label, "", "");

			sprintf(s, "sll $a1, $a1 %d", LOG_WSIZE);
			emit(fp, "", s, "multiply index by wordsize via SLL");

		}

		// loading var name since its global and we could just use name.
		sprintf(s, "la $a0, %s", p->name);
		emit(fp, "", s, "emit global var");
	} else {
		// local var (Stack pointer + offset)
		if (p->symbol->SubType == SYM_ARRAY){
			EMIT_EXPR(p->s1, fp);

			p->label = createLabel();

			emit(fp, "", "move $a1, $a0", "var copy index array in a1");

			emit(fp, "", "add $a0, $a0, 1", "");
			sprintf(s, "li $t1, %d", p->symbol->mysize);
			emit(fp, "", s, "");
			emit(fp, "", "slt $t0, $t1, $a0", "");
			sprintf(s, "beq $t0, $0, %s", p->label);
			emit(fp, "", s, "");

			emit(fp, "", "li $v0, 10", "");
			emit(fp, "", "syscall", "");

			fprintf(fp, "\n");
			emit(fp, p->label, "", "");

			emit(fp, "", "move $a1, $a0", "var copy index array in a1");
			sprintf(s, "sll $a1, $a1 %d", LOG_WSIZE);
			emit(fp, "", s, "multiply index by wordsize via SLL");
		}

		// loading var into memory
		emit(fp, "", "move $a0, $sp", "makes a copy of stack pointer and places in $a0");
		sprintf(s, "addi $a0, $a0, %d", p->symbol->offset * WSIZE);
		emit(fp, "", s, "stack pointer + offset");
	}

	// add on arr index if needed.
	if (p->symbol->SubType == SYM_ARRAY){
		emit(fp, "", "add $a0, $a0, $a1", "var array add internal offset");
	}

} // end of EMIT_VAR

// Pre: Pointer to A_FUNCTIONDEC node and pointer to MIPS asm file 
// Post: 
//	Prints instructions to MIPS asm file for function structure (including params). Includes 
//	implicit return depending on function name
void EMIT_FUNCTION(ASTnode *p, FILE *fp)
{
	char s[100];

	emit(fp, p->name, "", "function definition");
	emit(fp, "", "move $a1, $sp", "Activation Record carve out copy SP");
	sprintf(s, "subi $a1, $a1, %d", p->symbol->offset * WSIZE);
	emit(fp, "", s, "Activation Record carve out of function");
	emit(fp, "", "sw $ra, ($a1)", "Store return address");
	sprintf(s, "sw $sp %d($a1)", WSIZE);
	emit(fp, "", s, "Store old stack pointer");
	emit(fp, "", "move $sp, $a1", "Make SP the current activation record");
	fprintf(fp, "\n\n");

	// Copy the paramters to the formal from regster $t0 s1 linked
	ASTnode *Args = p->symbol->fparms;

	// Function counter 
	int counter = 0;

	while (Args != NULL){
		sprintf(s, "sw $t%d, %d($sp)", counter++, Args->symbol->offset * WSIZE);
		emit(fp, "", s, "Paramater store start of function");
		Args = Args->next;
	}

	fprintf(fp, "\n");

	// generate the compound statement
	EMIT_AST(p->s2, fp);

	// Restore ra and sp before we return
	emit(fp, "", "lw $ra ($sp)", "Restore old env RA");
	sprintf(s, "lw $sp, %d($sp)", WSIZE);
	emit(fp, "", s, "return from function restore sp");
	fprintf(fp, "\n");

	// Implicit return at the end of main
	if (strcmp(p->name, "main") == 0){
		// exit the system
		emit(fp, "", "li $v0, 10", "Exit from main, we are done.");
		emit(fp, "", "syscall", "Exit everything");
	} else {
		// jump back to the caller
		emit(fp, "", "jr $ra", "return to the caller");
		fprintf(fp, "\n");
	}
} // end of EMIT_FUNCTION

