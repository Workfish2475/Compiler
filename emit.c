// Pre: Pointer to A_WHILE node and pointer to MIPS asm file
// Post: 
// 	Prints instructions to MIPS asm file for while statements and emits asm code corresponding
// 	to a while loop structure 
void EMIT_WHILE(ASTnode *p, FILE *fp)
{
	char s[100];

	// create both labels here
	p->label = createLabel();
	sprintf(s, "\n%s", p->label);
	emit(fp, s, "", "");

	// emit the expression and do comparisons
	EMIT_EXPR(p->s1, fp);
	EMIT_AST(p->s2, fp);

	sprintf(s, "j %s", p->label);
	emit(fp, "", s, "WHILE Jump back");

	emit(fp, p->s1->label, "", "");

} // end of EMIT_WHILE

