// Global counter variable to keep track of label numbers
int labelCount = 0;

// Pre: None. Depends on global labelCount var to keep track of label counts. 
// Post: Returns a pointer to a newly created unique label string. Each label is formatted as "_Lx", where 'x' is a unique number (tracked by labelCount).
char *createLabel()
{
	char hold[100];
	char *s;
	sprintf(hold, "_L%d", labelCount++);
	s = strdup(hold);
	return (s);
} // end of createLabel

// Pre: Pointer to AST and pointer to MIPS asm file
// Post: Prints out MIPS code to asm file. Parses tree with helper function
void EMIT(ASTnode *p, FILE *fp)
{
	// Checks if either pointer is null
	if (p == NULL || fp == NULL)
	{
		return;
	}

	fprintf(fp, "# MIPS CODE GENERATED BY CS370\n");
	fprintf(fp, "\n.data\n");
	EMIT_STRINGS(p, fp); //emits strings using labels
	fprintf(fp, "\n.align 2\n");
	EMIT_GLOBALS(p, fp); //emits global vars 
	fprintf(fp, "\n.text\n\n");
	fprintf(fp, ".globl main\n\n");
	EMIT_AST(p, fp); //starts parsing the tree
	return;
} // end of EMIT

// Pre: Pointer to vars that are declared in the global scope
// POST: Prints global vars to MIPS code to file
void EMIT_GLOBALS(ASTnode *p, FILE *fp)
{

	if (p == NULL){
		return;
	}

	// Checks if node is variable and if it is global.
	if (p->type == A_VARDEC && p->symbol->level == 0){
		fprintf(fp, "%s: .space %d # Global variable\n", p->name, p->symbol->mysize * WSIZE);
	}

	EMIT_GLOBALS(p->s1, fp);
	EMIT_GLOBALS(p->s2, fp);
	EMIT_GLOBALS(p->next, fp);
} // end of EMIT_GLOBALS

// Pre: Pointer to A_WRITE node and pointer to MIPS asm file
// Post: Prints string labels with corresponding values to MIPS asm file
void EMIT_STRINGS(ASTnode *p, FILE *fp)
{
	if (p == NULL){
		return;
	}

	// Checks if node is write and if name has value.
	if (p->type == A_WRITE && p->name != NULL){
		p->label = createLabel();
		fprintf(fp, "%s: .asciiz\t %s\n", p->label, p->name);
	}

	EMIT_STRINGS(p->s1, fp);
	EMIT_STRINGS(p->s2, fp);
	EMIT_STRINGS(p->next, fp);
} // end of EMIT_STRINGS

// Pre: Pointer to Abstract syntax tree
// Post: Parses AST via a switch statement for various nodes. 
void EMIT_AST(ASTnode *p, FILE *fp)
{
	if (p == NULL){
		return;
	}

	switch (p->type){
	case A_VARDEC:
		EMIT_AST(p->next, fp); // Next statement 
		break;
	case A_FUNCTIONDEC:
		EMIT_FUNCTION(p, fp);
		EMIT_AST(p->next, fp); // Next statement 
		break;
	case A_WRITE:
		EMIT_WRITE(p, fp);
		EMIT_AST(p->next, fp); // Next statement 
		break;
	case A_COMPOUND:
		EMIT_AST(p->s2, fp);
		EMIT_AST(p->next, fp); // Next statement 
		break;
	case A_READ:
		EMIT_READ(p, fp);
		EMIT_AST(p->next, fp); // Next statement 
		break;
	case A_ASSIGN:
		EMIT_ASSIGN(p, fp);
		EMIT_AST(p->next, fp); // Next statement 
		break;
	case A_WHILE:
		EMIT_WHILE(p, fp);
		EMIT_AST(p->next, fp); // Next statement 
		break;
	case A_IF:
		EMIT_IF(p, fp);
		EMIT_AST(p->next, fp); // Next statement 
		break;
	case A_EXPRSTMT:
		EMIT_EXPR(p->s1, fp);
		EMIT_AST(p->next, fp); // Next statement 
		break;
	case A_RETURN:
		EMIT_RETURN(p, fp);
		break;
	default:
		printf("Type: %d\n", p->type);
		printf("WE SHOULD NOT BE HERE\n");
		break;
	}

} // end of EMIT_AST

// Pre:
//    FILE *fp - A pointer to the file where the assembly code will be emitted. The file must be open for writing.
//    char *label - A string representing the label for the assembly instruction. If empty, no label is written.
//    char *command - A string representing the assembly command. It should not be empty as it is the primary content.
//    char *comment - A string representing a comment to be appended to the assembly instruction. If empty, no comment is written.
// Post: Prints instructions to MIPS asm file in a format that corresponds input. 
void emit(FILE *fp, char *label, char *command, char *comment)
{
	if (strcmp("", comment) == 0)
	{
		if (strcmp("", label) == 0){
			fprintf(fp, "\t%s\t\t\n", command);
		} else {
			fprintf(fp, "%s:\t%s\t\t\n", label, command);
		}
	} else {
		if (strcmp("", label) == 0){
			fprintf(fp, "\t%s\t\t# %s\n", command, comment);
		} else {
			fprintf(fp, "%s:\t%s\t\t# %s\n", label, command, comment);
		}
	}
} // end of emit

// Pre: Pointer to A_WRITE node and pointer to MIPS asm file
// Post: Prints instructions to MIPS asm file depending of if node has a name or not. 
void EMIT_WRITE(ASTnode *p, FILE *fp)
{

	char s[100];

	// Checks if writing string or expression
	if (p->name != NULL){
		sprintf(s, "la $a0, %s", p->label);
		emit(fp, "", s, "String address");
		emit(fp, "", "li  $v0, 4", "About to print a string");
		emit(fp, "", "syscall", "call write string");
		fprintf(fp, "\n\n");
	} else {
		EMIT_EXPR(p->s1, fp);
		emit(fp, "", "li $v0, 1", "About to print a number");
		emit(fp, "", "syscall", "call write number");
		fprintf(fp, "\n\n");
	}
} // end of EMIT_WRITE

// Pre: Pointer to A_EXPR/A_NUM/A_VAR/A_CAll node and pointer to MIPS asm file 
// Post: 
// 	Prints instructions to MIPS asm file depending on node type. Does case
// 	for initial type, then does additional case analysis if type is A_EXPR
void EMIT_EXPR(ASTnode *p, FILE *fp)
{
	char s[100];

	switch (p->type){
	case A_NUM:
		sprintf(s, "li $a0, %d", p->value);
		emit(fp, "", s, "expr is constant");
		break;

	case A_EXPR:

		EMIT_EXPR(p->s1, fp);
		sprintf(s, "sw $a0, %d($sp)", p->symbol->offset * WSIZE);
		emit(fp, "", s, "expression store LHS temporarily");
		EMIT_EXPR(p->s2, fp);
		emit(fp, "", "move $a1, $a0", "right hand side needs to be a1");
		sprintf(s, "lw $a0, %d($sp)", p->symbol->offset * WSIZE);
		emit(fp, "", s, "expression restore LHS from memory");

		switch (p->operator)
		{
		case A_PLUS:
			emit(fp, "", "add $a0, $a0, $a1", "EXPR ADD");
			break;
		case A_MINUS:
			emit(fp, "", "sub $a0, $a0, $a1", "EXPR SUB");
			break;
		case A_TIMES:
			emit(fp, "", "mult $a0 $a1", "EXPR MULT");
			emit(fp, "", "mflo $a0", "EXPR MULT");
			break;
		case A_DIVIDE:
			emit(fp, "", "div $a0 $a1", "EXPR DIV");
			emit(fp, "", "mflo $a0", "EXPR DIV");
			break;
		case A_LT:
			p->label = createLabel();
			emit(fp, "", "slt $a0, $a0, $a1", "EXPR LESS THAN");
			sprintf(s, "beq $a0, $0, %s", p->label);
			emit(fp, "", s, "branch out");
			break;
		case A_LE:
			p->label = createLabel();
			emit(fp, "", "add $a1, $a1, 1", "EXPR LE add one to do compare");
			emit(fp, "", "slt $a0, $a0, $a1", "EXPR LE");
			sprintf(s, "beq $a0, $0, %s", p->label);
			emit(fp, "", s, "branch out");
			break;
		case A_GT:
			p->label = createLabel();
			emit(fp, "", "slt $a0, $a1, $a0", "EXPR Greaterthan");
			sprintf(s, "beq $a0, $0, %s", p->label);
			emit(fp, "", s, "branch out");
			break;
		case A_GE:
			p->label = createLabel();
			emit(fp, "", "add $a0, $a0, 1", "EXPR  ADD GE");
			emit(fp, "", "slt $a0, $a1, $a0", "EXPR Greaterthan");
			sprintf(s, "beq $a0, $0, %s", p->label);
			emit(fp, "", s, "branch out");
			break;
		case A_EQ:
			p->label = createLabel();
			emit(fp, "", "slt $t2 ,$a0, $a1", "EXPR EQUAL");
			emit(fp, "", "slt $t3 ,$a1, $a0", "EXPR EQUAL");
			emit(fp, "", "nor $a0 ,$t2, $t3", "EXPR EQUAL");
			emit(fp, "", "andi $a0, 1", "EXPR EQUAL");
			sprintf(s, "beq $a0, $0, %s", p->label);
			emit(fp, "", s, "branch out");
			break;
		case A_NE:
			p->label = createLabel();
			emit(fp, "", "slt $t2 ,$a0, $a1", "EXPR NEQUAL");
			emit(fp, "", "slt $t3 ,$a1, $a0", "EXPR NEQUAL");
			emit(fp, "", "or $a0 ,$t2, $t3", "EXPR NEQUAL");
			sprintf(s, "beq $a0, $0, %s", p->label);
			emit(fp, "", s, "branch out");
			break;
		case A_MODULO:
			emit(fp, "", "div $a0 $a1", "EXPR DIV remainder");
			emit(fp, "", "mfhi $a0", "EXPR DIV remainder");
			break;
		default:
			printf("Case not accounted for: %d: ", p->operator);
			break;
		}
		break;

	case A_VAR:
		EMIT_VAR(p, fp);
		emit(fp, "", "lw $a0, ($a0)", "expression is a var");
		break;
	case A_CALL:
		EMIT_CALL(p, fp);
		break;
	default:
		printf("EMIT_EXPR should never be here\n FIX!");
		printf("Case not accounted for: %d\n", p->type);
	}

} // end of EMIT_EXPR

